def items_wrapped(collection: str, line_expr: str, qty_expr: str) -> str:
    """Line items without prices, where each entry wraps a line item
    (fulfillments: `line.line_item`, refunds: `line.line_item`)."""
    return fill(
        """                    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">
                      {%- for line in """
        + collection
        + """ -%}
                        {%- assign item = """
        + line_expr
        + """ -%}
                        {%- unless item.nested_line_child? -%}
                        <tr>"""
        + _thumb("item")
        + """
                          <td valign="top" style="padding: 2px 0 18px 4px; font-family: %FONT%;">
                            <div style="font-size:15px; font-weight:700; color:#ffffff; line-height:1.3;">{{ item.product.title | default: item.presentment_title | default: item.title }}</div>
                            {%- if item.variant.title != 'Default Title' and item.variant.title != blank -%}
                              <div style="font-size:13px; color:#9ca3af; margin-top:3px;">{{ item.variant.title }}</div>
                            {%- endif -%}
                            <div style="font-family: %MONO%; font-size:13px; color:#9ca3af; margin-top:3px;">Qty """
        + qty_expr
        + """</div>
                          </td>
                        </tr>
                        {%- endunless -%}
                      {%- endfor -%}
                    </table>
"""
    )


